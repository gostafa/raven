import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Build the preview from the same renderer used in Raven. Run from the repo root.
const renderer = readFileSync('frontend/src/features/folders/adapters/hairline/funcs.ts', 'utf8');
const figure = new Bun.Transpiler({ loader: 'ts', minifyWhitespace: true }).transformSync(renderer);
writeFileSync(
  new URL('./folder.js', import.meta.url),
  `/* Generated by build.ts from Raven's folder renderer. */\n${figure}\nhairline({
  name: "folder",
  means: "A folder opens under the pointer and fans its image and film papers above the cover.",
  rules: [1, 2, 5, 6, 7, 8, 9, 10],
  range: [4, 8, 12],
  tour: [[30, 160], [170, 180], [260, 140], null],
  mount: mountFolderFigure,
});\n`,
);
// Keep the skill's bench and kernel unchanged; use its assembly entry point.
const skillRoot = process.env.HAIRLINE_SKILL_ROOT ?? `${process.env.HOME}/.agents/skills/hairline-create`;
const result = Bun.spawnSync(
  [
    'bun',
    `${skillRoot}/build.mjs`,
    fileURLToPath(new URL('./folder.js', import.meta.url)),
    fileURLToPath(new URL('./hairline-folder.html', import.meta.url)),
  ],
  { stdout: 'inherit', stderr: 'inherit' },
);
if (result.exitCode !== 0) process.exit(result.exitCode);
